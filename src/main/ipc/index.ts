/**
 * Every channel that reads or writes the data folder, runs agents, talks to
 * providers / IM platforms, or serves files.
 *
 * In local mode these run in this process; in remote mode the backend serves the
 * exact same table and the desktop forwards to it (`src/main/remote/shell.ts`).
 * The client's proxy list is generated by running **these functions** with a
 * recording binder, so the two sides can never drift apart.
 *
 * Electron must not be reachable from this module tree: it is the backend's
 * entry (`src/main/server/bootstrap.ts` imports it). Desktop-only channels live
 * in `./local`.
 */
export function registerRemoteHandlers(bind: Binder): void {
  registerSettingsHandlers(bind);
  registerWorkdirHandlers(bind);
  registerThemeHandlers(bind);
  registerNetworkHandlers(bind);
  registerChatHandlers(bind);
  registerTagHandlers(bind);
  registerProjectHandlers(bind);
  registerCronHandlers(bind);
  registerMessageHandlers(bind);
  registerProviderHandlers(bind);
  registerSkillHandlers(bind);
  // Pluggable feature: its own master switch (see `SPEND_STATS_ENABLED`).
  if (SPEND_STATS_ENABLED) registerSpendHandlers(bind);
  // Pluggable feature: its own master switch (see `IMAGE_GENERATION_ENABLED`).
  if (IMAGE_GENERATION_ENABLED) registerImageGenHandlers(bind);
  registerMcpHandlers(bind);
  registerMiniAppHandlers(bind);
  registerAgentSessionHandlers(bind);
  registerEmployeeHandlers(bind);
  registerFileHandlers(bind);
  registerSessionHandlers(bind);
  registerIntegrationHandlers(bind);
  registerBackupHandlers(bind);
}
